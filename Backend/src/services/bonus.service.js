// ============================================================
// HELPERS
// ============================================================


// ------------------------------------------------------------
// Parse Date
// ------------------------------------------------------------

const parseDate = (
    value,
    fieldName
) => {

    const date =
        new Date(value);

    if (
        Number.isNaN(
            date.getTime()
        )
    ) {

        const error =
            new Error(
                `${fieldName} must be a valid date`
            );

        error.statusCode =
            400;

        throw error;
    }

    return date;
};


// ------------------------------------------------------------
// Round Money
// ------------------------------------------------------------

const roundMoney = (
    value
) => {

    return Number(
        Number(value).toFixed(2)
    );
};


// ------------------------------------------------------------
// Non-Negative Number
// ------------------------------------------------------------

const validateNonNegativeNumber = (
    value,
    fieldName
) => {

    const numberValue =
        Number(value);

    if (
        value === undefined ||
        value === null ||
        value === "" ||
        !Number.isFinite(
            numberValue
        ) ||
        numberValue < 0
    ) {

        const error =
            new Error(
                `${fieldName} must be greater than or equal to 0`
            );

        error.statusCode =
            400;

        throw error;
    }

    return numberValue;
};


// ------------------------------------------------------------
// Decimal To Number
// ------------------------------------------------------------

const decimalToNumber = (
    value
) => {

    if (
        value === null ||
        value === undefined
    ) {

        return 0;
    }

    return Number(value);
};


// ------------------------------------------------------------
// Start Of Day
// ------------------------------------------------------------

const startOfDay = (
    date
) => {

    const result =
        new Date(date);

    result.setHours(
        0,
        0,
        0,
        0
    );

    return result;
};


// ------------------------------------------------------------
// Service Error
// ------------------------------------------------------------

const createServiceError = (
    message,
    statusCode = 400
) => {

    const error =
        new Error(
            message
        );

    error.statusCode =
        statusCode;

    return error;
};


