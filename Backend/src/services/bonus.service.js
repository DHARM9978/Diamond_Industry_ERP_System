// ============================================================
// GET EMPLOYEE
// ============================================================

const getEmployeeById = async (
    employeeId,
    companyId
) => {

    const id =
        Number(employeeId);

    if (
        !Number.isInteger(id) ||
        id <= 0
    ) {

        throw createServiceError(
            "Invalid employeeId",
            400
        );
    }


    const employee =
        await prisma.employee.findFirst({

            where: {

                employeeId:
                    id,

                companyId:
                    Number(companyId)
            },

            include:
                employeeInclude
        });


    if (!employee) {

        throw createServiceError(
            "Employee not found",
            404
        );
    }


    return employee;
};


// ============================================================
// GET EXTRA WORK RECORDS
// ============================================================
//
// These are the ExtraWork records generated by Payroll.
//
// Payroll remains responsible for calculating:
// - regular working hours
// - shortage hours
// - extra hours
// - ExtraWork records
//
// Bonus service is responsible for managing the already
// calculated ExtraWork records.
// ============================================================

const getExtraWorkRecords = async (
    companyId,
    options = {}
) => {

    const status =
        options.status
            ? String(
                options.status
            ).toUpperCase()
            : "ACCUMULATED";


    const records =
        await prisma.extraWork.findMany({

            where: {

                status,

                employee: {

                    companyId:
                        Number(companyId)
                },

                ...(options.employeeId
                    ? {

                        employeeId:
                            Number(
                                options.employeeId
                            )
                    }
                    : {}),

                ...(options.fromDate ||
                    options.toDate
                    ? {

                        createdAt: {

                            ...(options.fromDate
                                ? {

                                    gte:
                                        parseDate(
                                            options.fromDate,
                                            "fromDate"
                                        )
                                }
                                : {}),

                            ...(options.toDate
                                ? {

                                    lte:
                                        parseDate(
                                            options.toDate,
                                            "toDate"
                                        )
                                }
                                : {})
                        }
                    }
                    : {})
            },

            include: {

                employee: {

                    include:
                        employeeInclude
                },

                payroll:
                    true,

                settlement:
                    true
            },

            orderBy: [

                {

                    createdAt:
                        "desc"
                },

                {

                    extraWorkId:
                        "desc"
                }
            ]
        });


    return records.map(
        (
            record
        ) => ({

            extraWorkId:
                record.extraWorkId,

            employeeId:
                record.employeeId,

            employee:
                record.employee,

            payrollId:
                record.payrollId,

            payPeriodStart:
                record.payroll
                    ? record.payroll.payPeriodStart
                    : null,

            payPeriodEnd:
                record.payroll
                    ? record.payroll.payPeriodEnd
                    : null,

            expectedHours:
                record.payroll
                    ? decimalToNumber(
                        record.payroll
                            .monthlyExpectedHours
                    )
                    : 0,

            regularWorkingHours:
                record.payroll
                    ? decimalToNumber(
                        record.payroll
                            .regularWorkingHours
                    )
                    : 0,

            extraHours:
                decimalToNumber(
                    record.extraHours
                ),

            status:
                record.status,

            settlementId:
                record.settlementId,

            createdAt:
                record.createdAt,

            updatedAt:
                record.updatedAt
        })
    );
};


